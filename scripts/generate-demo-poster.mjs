// Regenerates the experiment's preview after the maze or policy changes:
//   node scripts/generate-demo-poster.mjs
// Writes two files, both committed:
//   src/assets/gridworld-poster.svg  inlined by RLDemo, so it follows the site theme
//   src/styles/maze.css              --maze-* tokens derived from palette.js
import { writeFile } from 'node:fs/promises';
import { palettes } from '../public/demos/gridworld/palette.js';
import { MAP, COLS, START, GOAL, isWall, trainCheckpoints, rollout } from '../public/demos/gridworld/model.js';

// The poster is inlined into the page, so it reads the site's own variables and
// switches with the theme toggle. The light value stays as a standalone fallback.
const paint = (key) => `var(--maze-${key}, ${palettes.light[key]})`;
const tokens = (theme) => Object.entries(palettes[theme])
  .map(([key, value]) => `    --maze-${key}: ${value};`).join('\n');

const size = 52, left = 216, top = 50;
const center = (s) => [left + (s % COLS + .5) * size, top + (Math.floor(s / COLS) + .5) * size];
const trace = rollout(trainCheckpoints().get(800));
const cells = MAP.flatMap((row, r) => [...row].map((_, c) => {
  const state = r * COLS + c;
  const x = left + c * size + 2, y = top + r * size + 2;
  const fill = isWall(state) ? paint('wall') : state === GOAL ? paint('goal') : paint('cell');
  return `<rect x="${x}" y="${y}" width="48" height="48" rx="5" fill="${fill}"/>`
    + (isWall(state) ? `<rect x="${x + 8}" y="${y + 8}" width="32" height="32" rx="3" fill="${paint('wallInner')}"/>` : '');
})).join('');
const path = [START, ...trace.map((step) => step.state)].map((s) => center(s).join(',')).join(' ');
const [sx, sy] = center(START), [gx, gy] = center(GOAL);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 900 420" width="900" height="420" role="img" aria-label="A nine by six maze. The agent starts at the top left and a dotted trail reaches the goal star at the bottom right.">`
  + `<rect width="900" height="420" fill="${paint('background')}"/><g>${cells}</g>`
  + `<polyline points="${path}" fill="none" stroke="${paint('path')}" stroke-width="3" stroke-linecap="round" stroke-dasharray="1 8"/>`
  + `<text x="${gx}" y="${gy + 8}" text-anchor="middle" fill="${paint('star')}" font-family="Georgia,serif" font-size="29">★</text>`
  + `<circle cx="${sx}" cy="${sy}" r="15" fill="${paint('agent')}"/>`
  + `<g fill="${paint('eyes')}"><circle cx="${sx - 5}" cy="${sy - 2}" r="2.5"/><circle cx="${sx + 5}" cy="${sy - 2}" r="2.5"/></g>`
  + `<g fill="${paint('label')}" font-family="monospace" font-size="10" letter-spacing="1">`
  + `<text x="193" y="${sy + 3}" text-anchor="end">START</text><text x="707" y="${gy + 3}">GOAL</text>`
  + `<text x="450" y="392" text-anchor="middle">A LITTLE EXPLORATION GOES A LONG WAY.</text></g></svg>`;

const css = `/* Generated by scripts/generate-demo-poster.mjs from palette.js. Do not edit. */
@layer reset, base, components;

@layer base {
  :root {
${tokens('light')}
  }
  :root[data-theme="dark"] {
${tokens('dark')}
  }
}
`;

await writeFile(new URL('../src/assets/gridworld-poster.svg', import.meta.url), svg);
await writeFile(new URL('../src/styles/maze.css', import.meta.url), css);
console.log(`Poster and maze tokens written. Learned path: ${trace.length} steps, goal reached: ${trace.at(-1).done}.`);
